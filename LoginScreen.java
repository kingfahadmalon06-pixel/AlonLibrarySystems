    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String surname = jTextField1.getText().trim();
        String rawPassword = new String(jPasswordField3.getPassword()).trim();

        if (surname.isEmpty() || rawPassword.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both surname and password.",
                "Missing Information", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Hardcoded Admin Check
        if (surname.equalsIgnoreCase(ADMIN_SURNAME) && rawPassword.equals(ADMIN_PASSWORD)) {
            JOptionPane.showMessageDialog(this, "Admin Login Successful!");
            AdminDashboard admin = new AdminDashboard(surname);
            admin.setLocationRelativeTo(null);
            admin.setVisible(true);
            this.dispose();
            return;
        }

        // Student Database Check via Neo4j
        try (Driver driver = Neo4jConfig.getDriver();
            Session session = driver.session()) {

            String query = "MATCH (s:Student {surname: $surname}) RETURN s.password AS password";
            Result result = session.run(query, parameters("surname", surname));

            if (result.hasNext()) {
                Record record = result.next();
                String storedPasswordHash = record.get("password").asString("");
                String inputPasswordHash = Passwordutil.hash(rawPassword);

                if (inputPasswordHash.equals(storedPasswordHash)) {
                    JOptionPane.showMessageDialog(this, "Login Successful!");
                    StudentDashboard dashboard = new StudentDashboard(surname);
                    dashboard.setLocationRelativeTo(null);
                    dashboard.setVisible(true);
                    this.dispose();
                } else {
                    JOptionPane.showMessageDialog(this, "Invalid Surname or Password.", "Login Failed", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this, "Invalid Surname or Password.", "Login Failed", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

